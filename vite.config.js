import { sveltekit } from '@sveltejs/kit/vite';
import adapter from '@sveltejs/adapter-static';
import tailwindcss from '@tailwindcss/vite';
import { defineConfig } from 'vite';

export default defineConfig({
	plugins: [
		tailwindcss(),
		// SvelteKit 3 takes its config here (there is no svelte.config.js any more).
		sveltekit({
			adapter: adapter({
				// Static output goes to ./build  (the "publish directory" on Seenode)
				pages: 'build',
				assets: 'build',
				precompress: false,
				// Used by static hosts that show a custom 404 page (client-side error page)
				fallback: '404.html',
				strict: true
			}),
			prerender: {
				// robots.txt and sitemap.xml are generated by endpoints that no page links to,
				// so don't fail the build if the crawler doesn't reach them (CI checks they exist).
				handleUnseenRoutes: 'ignore'
			}
		})
	]
});
